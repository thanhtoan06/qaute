    @Override
    @Transactional
    public void seed() {
        LocalDateTime now = LocalDateTime.now().withNano(0);
        if (MANAGER_KEYS.length != MANAGER_EMAILS.length
                || MANAGER_KEYS.length != MANAGER_PRIMARY_CATEGORY_CODES.length) {
            throw new IllegalStateException("Các mảng quản lý demo không cùng số phần tử");
        }
        for (String categoryCode : CATEGORY_CODES) {
            boolean used = false;
            for (String appointmentCategoryCode : APPOINTMENT_CATEGORY_CODES) {
                if (categoryCode.equals(appointmentCategoryCode)) {
                    used = true;
                    break;
                }
            }
            if (!used) {
                throw new IllegalStateException("Thiếu lịch hẹn demo cho chuyên mục: " + categoryCode);
            }
        }
        List<ManagerData> managers = new ArrayList<>();

        for (int index = 0; index < MANAGER_EMAILS.length; index++) {
            String managerEmail = MANAGER_EMAILS[index];
            String primaryCategoryCode = MANAGER_PRIMARY_CATEGORY_CODES[index];
            User manager = user(managerEmail);
            Category rootCategory = categories.findByCode(primaryCategoryCode)
                    .orElseThrow(() -> new IllegalStateException(
                            "Chưa có chuyên mục gốc cho quản lý " + managerEmail));
            if (!scopes.isInScope(manager.getId(), rootCategory.getId())) {
                throw new IllegalStateException("Quản lý chưa được gán chuyên mục lịch hẹn: " + managerEmail);
            }
            Department department = departments.findById(rootCategory.getDepartmentId())
                    .orElseThrow(() -> new IllegalStateException(
                            "Chưa có phòng ban cho " + primaryCategoryCode));
            String location = department.getLocation() == null || department.getLocation().isBlank()
                    ? department.getName() : department.getName() + " – " + department.getLocation();
            ManagerData data = new ManagerData(manager, rootCategory, location, index + 1);
            managers.add(data);
            seedRules(data, now.toLocalDate());
            generation.generateForManager(manager.getId());
        }

        if (TOPICS.length != APPOINTMENT_CATEGORY_CODES.length
                || TOPICS.length != NOTES.length
                || TOPICS.length != APPOINTMENT_STATUSES.length
                || TOPICS.length != MODALITIES.length
                || TOPICS.length != OUTCOME_SUMMARIES.length
                || TOPICS.length != STUDENT_VISIBLE_SUMMARIES.length
                || TOPICS.length != CANCEL_REASONS.length) {
            throw new IllegalStateException("Các mảng dữ liệu lịch hẹn demo không cùng số phần tử");
        }

        int confirmedStudentIndex = 0;
        int historyStudentIndex = 0;
        for (int index = 0; index < TOPICS.length; index++) {
            String categoryCode = APPOINTMENT_CATEGORY_CODES[index];
            Category category = categories.findByCode(categoryCode)
                    .orElseThrow(() -> new IllegalStateException("Chưa có chuyên mục lịch hẹn demo: " + categoryCode));
            ManagerData manager = managers.get(managerIndexForCategory(categoryCode));
            if (!scopes.isInScope(manager.user().getId(), category.getId())) {
                throw new IllegalStateException("Quản lý chưa được gán chuyên mục lịch hẹn: " + categoryCode);
            }

            AppointmentStatus status = APPOINTMENT_STATUSES[index];
            int studentIndex = status == AppointmentStatus.CONFIRMED
                    ? (confirmedStudentIndex++ % STUDENT_COUNT)
                    : (historyStudentIndex++ * 7 + 3) % STUDENT_COUNT;
            if (index < REMOVED_LEGACY_STUDENT_DEMO_COUNT) {
                continue;
            }

            String studentEmail = (STUDENT_MSSV_START + studentIndex) + STUDENT_EMAIL_SUFFIX;
            User student = user(studentEmail);
            if (appointments.existsByStudentIdAndTopic(student.getId(), TOPICS[index])) {
                continue;
            }

            boolean past = status == AppointmentStatus.COMPLETED || status == AppointmentStatus.NO_SHOW;
            AppointmentSlot slot = past
                    ? historicalSlot(manager, now.toLocalDate().minusDays(index + 2L))
                    : futureSlot(manager, now);
            if (status != AppointmentStatus.CANCELLED) {
                slot.setStatus(SlotStatus.BOOKED);
                slots.save(slot);
            }

            Appointment appointment = new Appointment();
            appointment.setSlotId(slot.getId());
            appointment.setStudentId(student.getId());
            appointment.setManagerId(manager.user().getId());
            appointment.setCategoryId(category.getId());
            appointment.setTopic(TOPICS[index]);
            appointment.setNote(NOTES[index]);
            appointment.setModality(MODALITIES[index]);
            appointment.setStatus(status);
            appointment.setReminder24hSent(past);
            appointment.setReminder1hSent(past);
            if (status == AppointmentStatus.COMPLETED) {
                appointment.setOutcomeSummary(OUTCOME_SUMMARIES[index]);
                appointment.setStudentVisibleSummary(STUDENT_VISIBLE_SUMMARIES[index]);
            } else if (status == AppointmentStatus.CANCELLED) {
                appointment.setCancelledBy(student.getId());
                appointment.setCancelReason(CANCEL_REASONS[index]);
            }

            appointments.saveAndFlush(appointment);
            LocalDateTime created = past ? slot.getStartAt().minusDays(2) : now.minusDays(2);
            LocalDateTime updated = past ? slot.getEndAt() : now.minusHours(1);
            // CreationTimestamp tự đặt thời gian hiện tại khi insert; cập nhật lại để báo cáo có lịch sử.
            entityManager.createQuery("update Appointment a set a.createdAt = :created, a.updatedAt = :updated where a.id = :id")
                    .setParameter("created", created).setParameter("updated", updated)
                    .setParameter("id", appointment.getId()).executeUpdate();
        }
    }

    private void seedRules(ManagerData manager, LocalDate today) {
        List<AvailabilityRule> existing = rules.findByManagerIdOrderByDayOfWeekAscStartTimeAsc(manager.user().getId());
        List<AvailabilityRule> missing = new ArrayList<>();
        for (int day = 1; day <= 5; day++) {
            for (int hour : new int[]{9, 14}) {
                LocalTime start = LocalTime.of(hour, 0);
                LocalTime end = start.plusHours(2);
                int weekday = day;
                boolean alreadyDefined = existing.stream().anyMatch(rule -> rule.getDayOfWeek() == weekday
                        && start.equals(rule.getStartTime()) && end.equals(rule.getEndTime()));
                if (alreadyDefined) {
                    continue;
                }
                AvailabilityRule rule = new AvailabilityRule();
                rule.setManagerId(manager.user().getId());
                rule.setDayOfWeek(day);
                rule.setStartTime(start);
                rule.setEndTime(end);
                rule.setSlotMinutes(30);
                rule.setModality(Modality.BOTH);
                rule.setLocation(manager.location());
                rule.setMeetingLink(meetingLink(manager));
                rule.setValidFrom(today);
                rule.setActive(true);
                missing.add(rule);
            }
        }
        rules.saveAll(missing);
    }

    private AppointmentSlot futureSlot(ManagerData manager, LocalDateTime now) {
        return slots.findByManagerIdAndStartAtBetweenOrderByStartAtAsc(
                        manager.user().getId(), now.plusDays(2), now.plusDays(30)).stream()
                .filter(slot -> slot.getStatus() == SlotStatus.AVAILABLE)
                .filter(slot -> slot.getModality() == Modality.BOTH
                        && Duration.between(slot.getStartAt(), slot.getEndAt()).toMinutes() == 30)
                .filter(slot -> appointments.findBySlotIdIn(List.of(slot.getId())).isEmpty())
                .findFirst()
                .orElseThrow(() -> new IllegalStateException(
                        "Không có khung giờ tương lai phù hợp để tạo lịch hẹn demo cho " + manager.user().getEmail()));
    }

    private AppointmentSlot historicalSlot(ManagerData manager, LocalDate preferredDay) {
        for (int attempt = 0; attempt < 30; attempt++) {
            LocalDate candidate = preferredDay.minusDays(attempt);
            if (candidate.getDayOfWeek() == DayOfWeek.SATURDAY
                    || candidate.getDayOfWeek() == DayOfWeek.SUNDAY) {
                continue;
            }
            LocalDateTime start = candidate.atTime(9, 0);
            AppointmentSlot existing = slots.findByManagerIdAndStartAt(manager.user().getId(), start).orElse(null);
            if (existing != null) {
                continue;
            }
            AppointmentSlot slot = new AppointmentSlot();
            slot.setManagerId(manager.user().getId());
            slot.setStartAt(start);
            slot.setEndAt(start.plusMinutes(30));
            slot.setModality(Modality.BOTH);
            slot.setLocation(manager.location());
            slot.setMeetingLink(meetingLink(manager));
            slot.setStatus(SlotStatus.BOOKED);
            return slots.save(slot);
        }
        throw new IllegalStateException("Không tìm được slot quá khứ trống cho " + manager.user().getEmail());
    }

    private User user(String email) {
        return users.findByEmailIgnoreCase(email)
                .orElseThrow(() -> new IllegalStateException("Thiếu tài khoản demo " + email));
    }

    private String meetingLink(ManagerData manager) {
        return "https://meet.example.com/qaute-advisor-" + manager.number();
    }

    private int managerIndexForCategory(String categoryCode) {
        int separator = categoryCode.indexOf('_');
        if (separator <= 0) {
            throw new IllegalStateException("Mã chuyên mục không hợp lệ: " + categoryCode);
        }
        String prefix = categoryCode.substring(0, separator);
        for (int index = 0; index < MANAGER_KEYS.length; index++) {
            if (MANAGER_KEYS[index].equals(prefix)) {
                return index;
            }
        }
        throw new IllegalStateException("Chưa ánh xạ quản lý cho chuyên mục: " + categoryCode);
    }

